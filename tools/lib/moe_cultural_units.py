def _stats(unit, lang):
    u = UNITS[unit]
    c = ('、' if lang == 'simp_chinese' else ', ').join(f'[{_CONCEPT[a]}|E]' for a in u['counters'])
    if lang == 'simp_chinese':
        s = (f"[{_CONCEPT[u['type']]}|E]，伤害 #V {u['damage']}#!、韧性 #V {u['toughness']}#!、"
             f"追击 #V {u['pursuit']}#!、掩护 #V {u['screen']}#!，克制{c}；"
             f"招募 #V {u['buy']}#! [gold|E]，维护 #V {u['low']:g}#!/#V {u['high']:g}#! [gold|E]")
        if 'max_sub_regiments' in u:
            s += f"；限 #V 1#! 支，最多 #V {u['max_sub_regiments']}#! 队 × {u['stack']} 人"
        return s
    s = (f"[{_CONCEPT[u['type']]}|E], damage #V {u['damage']}#!, toughness #V {u['toughness']}#!, "
         f"pursuit #V {u['pursuit']}#!, screen #V {u['screen']}#!, counters {c}; "
         f"recruitment #V {u['buy']}#! [gold|E], maintenance #V {u['low']:g}#!/#V {u['high']:g}#! [gold|E]")
    if 'max_sub_regiments' in u:
        s += f"; limited to #V 1#! regiment of up to #V {u['max_sub_regiments']}#! × {u['stack']} soldiers"
    return s


