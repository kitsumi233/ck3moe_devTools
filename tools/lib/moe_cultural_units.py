def culture_override(core_culture_text):
    """Complete Moe culture derived from core: add both traditions and Ratkin/cosplay unit gfx."""
    text, n = re.subn(r'unit_gfx\s*=\s*\{[^}]*\}', 'unit_gfx = { ' + ' '.join(UNIT_GFX) + ' }', core_culture_text)
    if n != 1:
        raise ValueError('core Moe culture must have exactly one unit_gfx block')
    m = re.search(r'(\n(\t+)traditions\s*=\s*\{)(.*?)(\n\2\})', text, re.S)
    if not m:
        raise ValueError('core Moe culture has no traditions block')
    if any(t in m.group(3) for t in TRADITIONS):
        raise ValueError('core Moe culture must not list the package traditions')
    added = ''.join(f'\n{m.group(2)}\t{t}' for t in TRADITIONS)
    text = text[:m.end(3)] + added + text[m.end(3):]
    return ('# Complete Moe culture override generated from moe_core (same path replaces it).\n'
            '# Adds Cosplay Identity + Humanoid Mercenaries and Ratkin/cosplay unit graphics.\n' + text)


def files(game, core_culture_text, pose_summary):
    """{relative path: text}. pose_summary: {language: pose list used in the welcome text}."""
    welcome = {lang: CR.welcome_description(lang, 0, pose_summary[lang], culture_pack=True)
               for lang in ('english', 'simp_chinese')}
    out = CR.culture_pack_files(game, welcome)
    out[CR.HUMANOID_MERCENARIES_REL] = HUMANOID_TRADITION_TEXT
    out[CULTURE_REL] = culture_override(core_culture_text)
    out[MAA_REL] = maa_text()
    for lang in ('english', 'simp_chinese'):
        trad, units = localization(lang)
        out[CR.TRADITION_LOC_REL.format(lang=lang)] += trad
        out[UNIT_LOC_REL.format(lang=lang)] = units
    return out


def binaries():
    """{packaged relative path: source path} for the tradition illustrations."""
    return {f'{ICON_DIR}/{name}': ROOT / src for name, src in ICONS.items()}
